#!/usr/bin/env python3
"""Encode the artist's transparent QR caption into three 1-bit color masks."""
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parent
COLORS=((16,135,165),(6,82,101),(0,0,0)) # fixed skin pens 242,245,254

def encode():
    source=Image.open(ROOT/'assets/game-manual.png').convert('RGBA')
    assert source.size==(25,12)
    assert all(a in (0,255) for r,g,b,a in source.getdata())
    assert all((r,g,b) in COLORS for r,g,b,a in source.getdata() if a)
    data=bytearray()
    for scale in (1,2):
        image=source.resize((25*scale,12*scale),Image.Resampling.NEAREST)
        pixels=list(image.getdata());stride=((image.width+15)//16)*2
        for color in COLORS:
            mask=bytearray(stride*image.height)
            for y in range(image.height):
                for x in range(image.width):
                    r,g,b,a=pixels[y*image.width+x]
                    if a and color!=(0,0,0) and (r,g,b)==color:mask[y*stride+x//8]|=1<<(7-x%8)
            data+=mask
    assert len(data)==720
    return bytes(data)

if __name__=='__main__':
    data=encode()
    text='; Generated by encode_qr_label.py; 25x12 then 50x24; pens 242,245; all black is transparent (third mask empty).\n'
    text+='label_pixels:\n'
    text+='\n'.join(' dc.b '+','.join(f'${v:02x}' for v in data[i:i+16]) for i in range(0,len(data),16))+'\n'
    (ROOT/'qr_label_image.i').write_text(text)
